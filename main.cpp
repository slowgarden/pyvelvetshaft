#include <string>
#include <vector>

void sum_evens() {
    int values[5] = {2, 4, 6, 8, 10};
    int acc = 0;
    for (int i = 0; i < 5; ++i) acc += values[i];
    (void)acc;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

void digit_count() {
    int n = 1234567;
    int digits = 0;
    while (n > 0) { digits += 1; n /= 10; }
    (void)digits;
}

void sum_pair() {
    int left = 3;
    int right = 9;
    int total = left + right;
    (void)total;
}

extern "C" int lunar_beacon();
extern void mellow_quartz();
extern void placid_hollow();

int main() {
    sum_evens();
    is_prime();
    digit_count();
    sum_pair();
    mellow_quartz();
    placid_hollow();
    return lunar_beacon();
}
